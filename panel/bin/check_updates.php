<?php
// Проверка обновлений панели (крон). Сверяет локальную версию с версией в
// репозитории оператора (адрес в Настройках) и кэширует результат в настройках —
// дашборд показывает баннер «доступно обновление», ничего не выкачивая.
//
// Запуск по cron, напр. раз в 6 часов:
//   0 */6 * * *  php /var/www/panel/bin/check_updates.php >/dev/null 2>&1

require __DIR__ . '/../src/bootstrap.php';

use App\UpdateChecker;

if (!UpdateChecker::configured()) {
    echo "Адрес проверки обновлений не задан (Настройки → Обновления) — пропускаю.\n";
    exit(0);
}

$s = UpdateChecker::check();
if ($s['error']) {
    fwrite(STDERR, "Проверка обновлений: ошибка — {$s['error']}\n");
    exit(1);
}
echo "Текущая: {$s['current']}; в репозитории: " . ($s['latest'] ?? '?')
    . ($s['update_available'] ? " — ДОСТУПНО ОБНОВЛЕНИЕ" : " — актуально") . "\n";
exit(0);
