    /** Значение настройки «использовать встроенный список» (Setting не умеет удалять ключ). */
    public const DEFAULT_MARK = '@default';

    public static function isDefault(?string $raw): bool
    {
        return $raw === null || trim($raw) === self::DEFAULT_MARK;
    }

    /** Домены из текста настройки (как NoRfGuard::parse: схема и путь отбрасываются). */
    public static function parseDomains(string $text): array
    {
        return NoRfGuard::parse($text);
    }

    /** IPv4/IPv6-подсети из текста: «1.2.3.0/24», одиночный IP → /32 (/128). */
    public static function parseCidrs(string $text): array
    {
        $out = [];
        foreach (preg_split('/[\s,]+/', preg_replace('/#[^\n]*/', '', $text)) as $tok) {
            $tok = trim($tok);
            if ($tok === '') {
                continue;
            }
            [$ip, $len] = array_pad(explode('/', $tok, 2), 2, null);
            $v6 = str_contains((string) $ip, ':');
            if (!filter_var($ip, FILTER_VALIDATE_IP)) {
                continue;
            }
            $max = $v6 ? 128 : 32;
            if ($len === null || $len === '') {
                $len = $max;
            }
            if (!ctype_digit((string) $len) || (int) $len < 8 || (int) $len > $max) {
                continue; // шире /8 — почти наверняка ошибка, не берём
            }
            $out["$ip/" . (int) $len] = true;
        }
        return array_keys($out);
    }

    /**
     * @param array    $routeRules правила (порядок как в sing-box)
     * @param string[] $domains    домены «только через РФ»
     * @param string[] $cidrs      подсети «только через РФ»
     * @param string[] $noRf       домены «без российского IP» — исключаются
     */
    public static function apply(array $routeRules, array $domains, array $cidrs, array $noRf = []): array
    {
        $domains = array_values(array_filter(array_unique($domains), function (string $d) use ($noRf) {
            foreach ($noRf as $n) {
                if ($d === $n || str_ends_with($d, '.' . $n) || str_ends_with($n, '.' . $d)) {
                    return false;
                }
            }
            return true;
        }));
        $cidrs = array_values(array_unique($cidrs));
        $head = [];
        if ($domains) {
            $head[] = ['domain_suffix' => $domains, 'outbound' => 'direct-rf'];
        }
        if ($cidrs) {
            $head[] = ['ip_cidr' => $cidrs, 'outbound' => 'direct-rf'];
        }
        return array_merge($head, $routeRules);
    }
